// Writes src/theme/cynosure-theme.css: tools' Cynosure theme as a static
// stylesheet, so the first paint already has it (tools#104). The theme is
// built from tools' own palette (src/theme/tokens.css), so Cynosure
// components look like the rest of the app. Run `pnpm theme:gen` after
// upgrading Cynosure or changing the palette; test/cynosure-theme.test.ts
// fails while the file is stale.
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import {
  createTheme,
  themeToCss,
  type ThemeInput,
} from '@arshad-shah/cynosure';

export const TOOLS_ACCENT = '#3ddc97';

/** tools' colour roles (tokens.css) in Cynosure's names, per mode. */
export const TOOLS_THEME: ThemeInput = {
  accent: TOOLS_ACCENT,
  font: {
    sans: "'Inter Variable', ui-sans-serif, system-ui, -apple-system, 'Segoe UI', Roboto, sans-serif",
    mono: "'JetBrains Mono Variable', ui-monospace, 'SF Mono', Menlo, Consolas, monospace",
  },
  palettes: {
    light: {
      bg: '#f6f7f9',
      surface: '#ffffff',
      surfaceRaised: '#f1f3f6',
      soft: '#e7eaef',
      line: '#e0e4ea',
      ink: '#0f1419',
      muted: '#4a5363',
      onAccent: '#04140c',
      accentText: '#0b794f',
      ring: '#0b794f',
      danger: '#c02727',
      dangerText: '#c02727',
      warning: '#975600',
      warningText: '#975600',
      info: '#1d5fc4',
      infoText: '#1d5fc4',
    },
    dark: {
      bg: '#0c0e12',
      surface: '#12151b',
      surfaceRaised: '#171b22',
      soft: '#1e232c',
      line: '#232934',
      ink: '#e8ebf0',
      muted: '#a3abba',
      onAccent: '#04140c',
      accentText: '#3ddc97',
      ring: '#3ddc97',
      danger: '#f87171',
      dangerText: '#f87171',
      warning: '#fbbf24',
      warningText: '#fbbf24',
      info: '#60a5fa',
      infoText: '#60a5fa',
    },
  },
};

export function cynosureThemeCss(): string {
  return `/* Generated by scripts/gen-cynosure-theme.ts from @arshad-shah/cynosure. Do not edit. */\n${themeToCss(createTheme(TOOLS_THEME))}\n`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync('src/theme/cynosure-theme.css', cynosureThemeCss());
}
