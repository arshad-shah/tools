// Writes the two theme files the first paint needs (redesign spec, rule 4):
// - src/theme/cynosure-theme.css: the tools theme as a static stylesheet, so
//   the first paint is already themed (CynosureTheme then applies the same
//   values to <html> at runtime);
// - public/theme-init.js: Cynosure's themeInitScript for the saved mode,
//   as a file because the content security policy forbids inline scripts.
// Run `pnpm theme:gen` after upgrading Cynosure or changing the theme;
// test/cynosure-theme.test.ts and test/theme-init.test.ts fail while either
// file is stale.
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { themeInitScript, themeToCss } from '@arshad-shah/cynosure';
import { THEME_KEY, toolsTheme } from '../src/theme/tools-theme';

export function cynosureThemeCss(): string {
  return `/* Generated by scripts/gen-cynosure-theme.ts from @arshad-shah/cynosure. Do not edit. */\n${themeToCss(toolsTheme)}\n`;
}

export function themeInitJs(): string {
  return `${themeInitScript({ key: THEME_KEY })}\n`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync('src/theme/cynosure-theme.css', cynosureThemeCss());
  writeFileSync('public/theme-init.js', themeInitJs());
}
