// Writes src/theme/cynosure-theme.css: tools' Cynosure theme (accent
// #3ddc97) as a static stylesheet, so the first paint already has it
// (tools#104). Run `pnpm theme:gen` after upgrading Cynosure;
// test/cynosure-theme.test.ts fails while the file is stale.
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { createTheme, themeToCss } from '@arshad-shah/cynosure';

export const TOOLS_ACCENT = '#3ddc97';

export function cynosureThemeCss(): string {
  return `/* Generated by scripts/gen-cynosure-theme.ts from @arshad-shah/cynosure. Do not edit. */\n${themeToCss(createTheme({ accent: TOOLS_ACCENT }))}\n`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync('src/theme/cynosure-theme.css', cynosureThemeCss());
}
